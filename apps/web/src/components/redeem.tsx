"use client";
import Link from "next/link";
import { useEffect, useRef, useState } from "react";
import { useRouter } from "next/navigation";
import { ArrowLeft, ShieldCheck } from "lucide-react";
import { api, Logo, Loading, ErrorBox } from "./ui";
export function Redeem({ owner = false }: { owner?: boolean }) {
  const started = useRef(false);
  const [error, setError] = useState("");
  const router = useRouter();
  useEffect(() => {
    if (started.current) return;
    started.current = true;
    const token = location.hash.slice(1);
    history.replaceState(null, "", location.pathname);
    if (!token) {
      setError(
        owner
          ? "Open the one-time sign-in link generated by pnpm owner:login."
          : "Open the full invitation link shared by your seller.",
      );
      return;
    }
    void api(owner ? "owner/redeem" : "invite/redeem", { token })
      .then((d) =>
        router.replace(owner ? "/workspace" : "/agreements/" + d.agreementId),
      )
      .catch((e) => setError(e.message));
  }, [owner, router]);
  return (
    <main className="auth-page">
      <Logo />
      <section className="auth-card panel">
        <ShieldCheck className="auth-icon" size={30} />
        <h1>
          {owner ? "Opening your studio." : "A clearer way to work together."}
        </h1>
        {error ? (
          <>
            <ErrorBox message={error} />
            <p>
              {owner
                ? "Sign-in links expire after 15 minutes and can be used once."
                : "Invitations are private and can be redeemed once. If you already opened this invitation, use the same browser to return to your workspace."}
            </p>
            <Link className="button secondary" href="/workspace">
              Open workspace
            </Link>
          </>
        ) : (
          <Loading message="Validating your private link…" />
        )}
        <Link className="back-link" href="/">
          <ArrowLeft size={15} />
          RevisionPay home
        </Link>
      </section>
    </main>
  );
}
